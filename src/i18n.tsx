export type Copy = { [K in keyof (typeof dict)['en']]: string }

interface I18nValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: Copy
  text: (value: Localized) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem(STORAGE)
    return saved === 'hy' || saved === 'en' || saved === 'ru' ? saved : 'en'
  })

  function setLang(next: Lang) {
    localStorage.setItem(STORAGE, next)
    setLangState(next)
  }

  useEffect(() => {
    document.documentElement.lang = lang === 'hy' ? 'hy' : lang
  }, [lang])

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t: dict[lang] as Copy,
      text: (value) => value[lang],
    }),
    [lang],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n outside provider')
  return value
}
